const CATS = {
    generating: "Generating code",
    wording: "Language and wording",
    look: "Look and layout",
    navigation: "Navigation and search",
    records: "History and messages",
    tools: "Tools and extensions",
    running: "Running it yourself",
};
const byId = Object.fromEntries(F.map((f) => [f[1], f]));
const root = new URL("../../docs/studio/", import.meta.url);
const index = [
    "# quicktype Studio documentation",
    "",
    "Every feature has its own article. Each covers what it does, how to use it, what happens when something goes wrong, privacy and security, and how to check it works.",
    "",
];
for (const [cat, title] of Object.entries(CATS)) {
    index.push(`## ${title}`, "");
    mkdirSync(new URL(`${cat}/`, root), { recursive: true });
    for (const [c, id, name, what, how, fail, sec, verify, related] of F.filter(
        (f) => f[0] === cat,
    )) {
        index.push(`- [${name}](${c}/${id}.md)`);
        const body = [
            `# ${name}`,
            "",
            what,
            "",
            "## How to use it",
            "",
            how,
            "",
            "## When something goes wrong",
            "",
            fail,
            "",
            "## Privacy and security",
            "",
            sec,
            "",
            "## How to check it works",
            "",
            verify,
            "",
            "## Suggested articles",
            "",
            ...related.map(
                (r) => `- [${byId[r][2]}](../${byId[r][0]}/${r}.md)`,
            ),
            "",
        ].join("\n");
        writeFileSync(new URL(`${c}/${id}.md`, root), body);
    }
    index.push("");
}
writeFileSync(new URL("README.md", root), index.join("\n"));
console.log(`${F.length} articles written`);
